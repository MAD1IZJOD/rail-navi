export function placeName(value:string,language:Language):string{
 if(language==="en")return value;
 if(value.endsWith(" access"))return placeName(value.slice(0,-7),language)+" तक पहुँचने का रास्ता";
 if(value.endsWith(" sign"))return placeName(value.slice(0,-5),language)+" का संकेत";
 return value.split(" · ").map(part=>{
  const direct=translate(part,language);if(direct!==part)return direct;
  const bridge=part.match(/^Foot Overbridge ([A-D])(.*)$/);if(bridge)return"पैदल ऊपरी पुल "+bridge[1]+bridge[2];
  if(part==="Lower passenger passage")return"निचला यात्री मार्ग";
  if(part==="South passenger underpass")return"दक्षिणी भूमिगत यात्री मार्ग";
  const side=part.match(/^(West|East|Central) ·? ?([0-9–]+)$/);if(side)return translate(side[1]!,language)+" · "+side[2];
  return part;
 }).join(" · ");
}
export function renderInstruction(step:RouteStep|undefined,language:Language):string{
 if(!step)return"";
 if(language==="en")return step.text;
 const a=step.action;
 if(!a)return"अगला रास्ता नक्शे पर देखें।";
 if(a.type==="arrive")return `आप ${placeName(a.target,language)} पर पहुँच गए हैं।${a.visit?" तैयार होने पर आगे बढ़ें।":""}`;
 if(a.type==="transition"){
  const mode={walk:"पैदल मार्ग",lift:"लिफ़्ट",stairs:"सीढ़ियाँ",escalator:"एस्केलेटर"}[a.connection];
  return `${placeName(a.via,language)} से ${mode} लेकर ${localFloor(a.toFloor,language)} पर ${a.ascending?"ऊपर":"नीचे"} जाएँ।`;
 }
 const dir={north:"उत्तर",south:"दक्षिण",east:"पूर्व",west:"पश्चिम"}[a.direction];
 return `${placeName(a.via,language)} पर ${dir} की ओर चलते हुए ${placeName(a.target,language)} तक जाएँ।`;
}
